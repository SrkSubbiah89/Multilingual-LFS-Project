"""
eval/build_wisco_isco_benchmark_v2_group_split.py

Conference I Reviewer #2 response, Step 7A, Phase C: v2 of the WISCO ISCO-08
controlled benchmark, built ONLY because
eval/audit_wisco_benchmark_leakage.py found real (if narrow) cross-split
leakage in v1: 4 pairs of DIFFERENT WISCO occupation keys share byte-
identical normalized title text in one language each (e.g. two distinct
WISCO entries for "Sworn translator" under unit group 2643) -- v1's
per-key split (eval/build_wisco_isco_benchmark.py) correctly keeps each
KEY's own language variants together, but has no way to know that two
DIFFERENT keys are, for leakage purposes, the same underlying occupation
family. See Documentation/Conference_I_Reviewer_2/
WISCO_LEAKAGE_AUDIT_AND_RUN_PLAN.md for the full audit.

v1 (eval/local_benchmarks/wisco_isco08_v1/) is NOT altered, deleted, or
regenerated by this script -- it remains on disk unchanged as the audit
record of the leakage finding (restriction: "retain v1 unchanged as an
audit record"). This script only ever writes to its own --out-root.

Grouping method (union-find over WISCO occupation keys)
---------------------------------------------------------
1. Start with one singleton group per occupation key.
2. For every language, for every set of >=2 keys that share an identical
   normalized (whitespace-collapsed, lowercased) title in that language,
   union those keys into one group.
3. Each resulting group (after path compression) is assigned ONE split,
   deterministically, from a sha256 hash of `f"{FIXED_SEED}:{sorted
   member keys joined by ','}"`, mod 10 (0 -> dev, else heldout) --
   reproducing v1's ~10%/90% ratio. FIXED_SEED is a literal constant
   recorded in this file and in build_summary.json -- changing it would
   systematically change the split in a documented, reproducible way; it
   is never read from an environment variable or CLI flag, so a rebuild
   from this exact script always reproduces the exact same split.
4. Every (occupation, language) record explodes exactly as v1's
   build_records() does, except split now comes from the record's GROUP,
   not its individual key.

Usage
-----
    python eval/build_wisco_isco_benchmark_v2_group_split.py \\
        --out-root eval/local_benchmarks/wisco_isco08_v2_group_split
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from collections import Counter, defaultdict
from datetime import datetime, timezone
from pathlib import Path

_HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(_HERE))

from controlled_benchmark_schema import (  # noqa: E402
    ADJUDICATION_UNKNOWN,
    BenchmarkRecord,
    DATA_SOURCE_EXTERNAL_AUTHORITATIVE,
    DOUBLE_CODING_UNKNOWN,
    INDEPENDENT_LABEL_STATUS_INDEPENDENT,
    ISCO08,
    LABEL_SOURCE_EXTERNAL_PUBLISHER,
    SPLIT_DEV,
    SPLIT_HELDOUT,
)
from dataset_card_schema import DEFAULT_DATASET_LABEL  # noqa: E402
from validate_controlled_benchmark import validate_benchmark_package  # noqa: E402
from audit_wisco_benchmark_leakage import normalize_text, run_full_audit  # noqa: E402
from build_wisco_isco_benchmark import (  # noqa: E402
    CLASSIFICATION_VERSION,
    LABELER,
    TARGET_LANGUAGES,
    WISCO_PARSED_PATH,
)

REPO_ROOT = _HERE.parent
FIXED_SEED = 42  # literal, documented constant -- see module docstring


class _UnionFind:
    def __init__(self, items):
        self.parent = {i: i for i in items}

    def find(self, x):
        root = x
        while self.parent[root] != root:
            root = self.parent[root]
        while self.parent[x] != root:
            self.parent[x], x = root, self.parent[x]
        return root

    def union(self, a, b):
        ra, rb = self.find(a), self.find(b)
        if ra != rb:
            self.parent[rb] = ra


def build_groups(wisco_records: list[dict]) -> dict:
    """Returns {source_key: group_root_key}."""
    keys = [str(occ["key"]) for occ in wisco_records]
    uf = _UnionFind(keys)

    text_to_keys: dict[tuple[str, str], list[str]] = defaultdict(list)
    for occ in wisco_records:
        key = str(occ["key"])
        for lang in TARGET_LANGUAGES:
            text = occ.get("titles", {}).get(lang)
            if text:
                text_to_keys[(lang, normalize_text(text))].append(key)

    n_merges = 0
    for (_lang, _text), matching_keys in text_to_keys.items():
        if len(matching_keys) < 2:
            continue
        first = matching_keys[0]
        for other in matching_keys[1:]:
            if uf.find(first) != uf.find(other):
                n_merges += 1
            uf.union(first, other)

    return {k: uf.find(k) for k in keys}, n_merges


def _split_for_group(group_root: str, member_keys: list[str]) -> str:
    payload = f"{FIXED_SEED}:{','.join(sorted(member_keys))}"
    digest = hashlib.sha256(payload.encode("utf-8")).hexdigest()
    return SPLIT_DEV if int(digest[:8], 16) % 10 == 0 else SPLIT_HELDOUT


def build_records(wisco_records: list[dict]) -> tuple[list[BenchmarkRecord], dict]:
    key_to_group, n_merges = build_groups(wisco_records)

    group_members: dict[str, list[str]] = defaultdict(list)
    for k, g in key_to_group.items():
        group_members[g].append(k)

    group_split = {g: _split_for_group(g, members) for g, members in group_members.items()}

    records: list[BenchmarkRecord] = []
    for occ in wisco_records:
        key = str(occ["key"])
        split = group_split[key_to_group[key]]
        gold_code = occ.get("isco08_unit", "")
        gold_title = occ.get("master_label_en", "")
        titles = occ.get("titles", {})
        for lang in TARGET_LANGUAGES:
            text = titles.get(lang)
            if not text:
                continue
            rec = BenchmarkRecord(
                benchmark_id=f"WISCO-{key}-{lang}",
                task=ISCO08,
                data_source_type=DATA_SOURCE_EXTERNAL_AUTHORITATIVE,
                dataset_label=DEFAULT_DATASET_LABEL,
                language=lang,
                input_text=text,
                context_fields=None,
                gold_code=gold_code,
                gold_code_title=gold_title,
                classification_standard="ISCO-08",
                classification_version=CLASSIFICATION_VERSION,
                hierarchy_level="unit_group_4digit",
                label_source_type=LABEL_SOURCE_EXTERNAL_PUBLISHER,
                labeler_identifier_or_role=LABELER,
                independent_label_status=INDEPENDENT_LABEL_STATUS_INDEPENDENT,
                double_coding_status=DOUBLE_CODING_UNKNOWN,
                adjudication_status=ADJUDICATION_UNKNOWN,
                ambiguity_flag=False,
                exclusion_reason=None,
                split=split,
            )
            payload = rec.model_dump_json(exclude={"record_hash"}, exclude_none=False).encode("utf-8")
            rec.record_hash = hashlib.sha256(payload).hexdigest()
            records.append(rec)

    meta = {
        "fixed_seed": FIXED_SEED,
        "n_source_keys": len(key_to_group),
        "n_groups": len(group_members),
        "n_merges_from_duplicate_text": n_merges,
        "n_groups_with_more_than_one_member": sum(1 for m in group_members.values() if len(m) > 1),
    }
    return records, meta


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out-root", type=Path, required=True)
    parser.add_argument("--wisco-parsed", type=Path, default=WISCO_PARSED_PATH)
    args = parser.parse_args()

    if not args.wisco_parsed.exists():
        parser.error(f"WISCO parsed file not found: {args.wisco_parsed}")

    wisco_records = json.loads(args.wisco_parsed.read_text(encoding="utf-8"))
    records, group_meta = build_records(wisco_records)

    args.out_root.mkdir(parents=True, exist_ok=True)

    records_payload = [json.loads(r.model_dump_json()) for r in records]
    dataset_hash = hashlib.sha256(
        json.dumps(records_payload, sort_keys=True, ensure_ascii=False).encode("utf-8")
    ).hexdigest()

    validation_report = validate_benchmark_package(records, dataset_hash=dataset_hash)
    leakage_report = run_full_audit(records_payload, expected_dataset_hash=dataset_hash)

    (args.out_root / "records.json").write_text(
        json.dumps({"records": records_payload}, indent=2, ensure_ascii=False), encoding="utf-8",
    )
    (args.out_root / "dataset_hash.txt").write_text(dataset_hash + "\n", encoding="utf-8")

    dev_ids = [r.benchmark_id for r in records if r.split == SPLIT_DEV]
    heldout_ids = [r.benchmark_id for r in records if r.split == SPLIT_HELDOUT]
    split_manifest = {
        "dataset_id": "WISCO-ISCO08-BENCHMARK-v2-group-split",
        "split_hash": hashlib.sha256((",".join(sorted(dev_ids)) + "|" + ",".join(sorted(heldout_ids))).encode("utf-8")).hexdigest(),
        "splits": {
            "dev": {"split_id": f"WISCO-ISCO08-V2-DEV-{len(dev_ids)}", "purpose": "parameter selection only", "n_cases": len(dev_ids), "frozen": False},
            "heldout": {"split_id": f"WISCO-ISCO08-V2-HELDOUT-{len(heldout_ids)}", "purpose": "frozen confirmation set", "n_cases": len(heldout_ids), "frozen": True},
        },
        "leakage_check_performed": True,
        "leakage_check_method": (
            "group-aware: WISCO occupation keys are union-find-merged into families whenever two keys "
            "share byte-identical normalized title text in any target language, then each family is "
            "assigned exactly one split via a fixed-seed (42) sha256 hash of its sorted member keys -- "
            "see this script's module docstring and FIXED_SEED"
        ),
    }
    (args.out_root / "split_manifest.json").write_text(json.dumps(split_manifest, indent=2, ensure_ascii=False), encoding="utf-8")

    lang_counts = Counter(r.language for r in records)
    split_counts = Counter(r.split for r in records)
    summary = {
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "supersedes_for_split_purposes": "eval/local_benchmarks/wisco_isco08_v1/ (retained unchanged as audit record -- see WISCO_LEAKAGE_AUDIT_AND_RUN_PLAN.md)",
        "reason_for_v2": "v1's leakage audit found 4 cross-split exact-duplicate-text groups (different WISCO keys, identical normalized title in one language, same gold code) -- see WISCO_LEAKAGE_AUDIT_AND_RUN_PLAN.md Phase B",
        "source_file": str(args.wisco_parsed.relative_to(REPO_ROOT)),
        "source_file_sha256": hashlib.sha256(args.wisco_parsed.read_bytes()).hexdigest(),
        "n_source_occupations": len(wisco_records),
        "n_benchmark_records": len(records),
        "language_counts": dict(lang_counts),
        "split_counts": dict(split_counts),
        "dataset_hash": dataset_hash,
        "grouping": group_meta,
        "validation_report": {"ok": validation_report.ok, "errors": validation_report.errors, "warnings": validation_report.warnings},
        "leakage_audit_summary": {
            "leakage_found": leakage_report["leakage_found"],
            "overall_ok_no_leakage": leakage_report["overall_ok_no_leakage"],
            "n_leaking_source_keys": leakage_report["source_family_split_check"]["n_leaking_source_keys"],
            "n_exact_duplicate_groups_cross_split": leakage_report["text_duplicate_check"]["n_exact_duplicate_groups_cross_split"],
        },
    }
    (args.out_root / "build_summary.json").write_text(json.dumps(summary, indent=2, ensure_ascii=False), encoding="utf-8")

    print(f"Wrote {len(records)} benchmark records ({dict(split_counts)}) to {args.out_root}")
    print(f"dataset_hash={dataset_hash}")
    print(f"group_meta={group_meta}")
    print(f"validation: ok={validation_report.ok} errors={len(validation_report.errors)}")
    print(f"leakage audit: leakage_found={leakage_report['leakage_found']} overall_ok={leakage_report['overall_ok_no_leakage']}")


if __name__ == "__main__":
    main()
